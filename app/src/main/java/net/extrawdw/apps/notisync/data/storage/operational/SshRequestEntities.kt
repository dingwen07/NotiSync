package net.extrawdw.apps.notisync.data.storage.operational

import androidx.room3.ColumnInfo
import androidx.room3.Entity
import androidx.room3.Index

/** One durable record is used for both active requests and review history. */
@Entity(
    tableName = "ssh_requests",
    primaryKeys = ["request_id"],
    indices = [
        Index(value = ["state", "updated_at"], name = "ssh_requests_state_idx"),
        Index(value = ["state", "expires_at"], name = "ssh_requests_expiry_idx"),
        Index(value = ["updated_at", "request_id"], name = "ssh_requests_history_idx"),
    ],
)
internal data class SshProviderRequestEntity(
    @ColumnInfo(name = "request_id") val requestId: String,
    @ColumnInfo(name = "kind") val kind: String,
    @ColumnInfo(name = "requester_client_id") val requesterClientId: String,
    @ColumnInfo(name = "request_fingerprint", typeAffinity = ColumnInfo.BLOB) val requestFingerprint: ByteArray,
    @ColumnInfo(name = "state") val state: String,
    @ColumnInfo(name = "outcome") val outcome: String?,
    @ColumnInfo(name = "result_at") val resultAt: Long?,
    @ColumnInfo(name = "updated_at") val updatedAt: Long,
    @ColumnInfo(name = "request_complete") val requestComplete: Int,
    @ColumnInfo(name = "requested_at") val requestedAt: Long,
    @ColumnInfo(name = "expires_at") val expiresAt: Long,
    @ColumnInfo(name = "public_key_blob", typeAffinity = ColumnInfo.BLOB) val publicKeyBlob: ByteArray?,
    @ColumnInfo(name = "key_name") val keyName: String?,
    @ColumnInfo(name = "suggested_name") val suggestedName: String?,
    @ColumnInfo(name = "import_source_type") val importSourceType: String?,
    @ColumnInfo(name = "encrypted_import") val encryptedImport: Int,
    @ColumnInfo(name = "signature_algorithm") val signatureAlgorithm: String?,
    @ColumnInfo(name = "destination_username") val destinationUsername: String?,
    @ColumnInfo(name = "destination_host") val destinationHost: String?,
    @ColumnInfo(name = "destination_host_key_fingerprint") val destinationHostKeyFingerprint: String?,
    @ColumnInfo(name = "payload_size") val payloadSize: Int,
    @ColumnInfo(name = "approval_kind") val approvalKind: String?,
    @ColumnInfo(name = "remembered_authorization_id") val rememberedAuthorizationId: String?,
    @ColumnInfo(name = "remembered_scope") val rememberedScope: String?,
    @ColumnInfo(name = "sign_data", typeAffinity = ColumnInfo.BLOB) val signData: ByteArray?,
    @ColumnInfo(name = "sign_flags") val signFlags: Long?,
    @ColumnInfo(name = "authorization_generation") val authorizationGeneration: String?,
    @ColumnInfo(name = "authorization_epoch") val authorizationEpoch: Long?,
    @ColumnInfo(name = "process_lineage_json") val processLineageJson: String,
    @ColumnInfo(name = "eligible_provider_client_ids_json") val eligibleProviderClientIdsJson: String?,
    @ColumnInfo(name = "host_aliases_json") val hostAliasesJson: String?,
    @ColumnInfo(name = "binding_chain_json") val bindingChainJson: String?,
    @ColumnInfo(name = "process_source") val processSource: String?,
    @ColumnInfo(name = "process_boot_id") val processBootId: String?,
    @ColumnInfo(name = "destination_provenance") val destinationProvenance: String?,
    @ColumnInfo(name = "connection_direction") val connectionDirection: String?,
    @ColumnInfo(name = "destination_service") val destinationService: String?,
    @ColumnInfo(name = "destination_authentication_method") val destinationAuthenticationMethod: String?,
    @ColumnInfo(name = "session_id_sha256", typeAffinity = ColumnInfo.BLOB) val sessionIdSha256: ByteArray?,
    @ColumnInfo(name = "server_host_key_blob", typeAffinity = ColumnInfo.BLOB) val serverHostKeyBlob: ByteArray?,
    @ColumnInfo(name = "server_host_key_blob_sha256", typeAffinity = ColumnInfo.BLOB) val serverHostKeyBlobSha256: ByteArray?,
    @ColumnInfo(name = "connection_id") val connectionId: String?,
    @ColumnInfo(name = "confirmation_required") val confirmationRequired: Int?,
    @ColumnInfo(name = "import_file_bytes", typeAffinity = ColumnInfo.BLOB) val importFileBytes: ByteArray?,
    @ColumnInfo(name = "import_agent_identity", typeAffinity = ColumnInfo.BLOB) val importAgentIdentity: ByteArray?,
    @ColumnInfo(name = "import_lifetime_seconds") val importLifetimeSeconds: Long?,
    @ColumnInfo(name = "import_confirmation_required") val importConfirmationRequired: Int?,
    @ColumnInfo(name = "response_kind") val responseKind: String?,
    @ColumnInfo(name = "response_provider_client_id") val responseProviderClientId: String?,
    @ColumnInfo(name = "response_public_key_sha256", typeAffinity = ColumnInfo.BLOB) val responsePublicKeySha256: ByteArray?,
    @ColumnInfo(name = "response_signature_blob", typeAffinity = ColumnInfo.BLOB) val responseSignatureBlob: ByteArray?,
    @ColumnInfo(name = "response_remember_disposition") val responseRememberDisposition: String?,
    @ColumnInfo(name = "response_authorization_generation") val responseAuthorizationGeneration: String?,
    @ColumnInfo(name = "response_authorization_epoch") val responseAuthorizationEpoch: Long?,
    @ColumnInfo(name = "response_rejection_reason") val responseRejectionReason: String?,
    @ColumnInfo(name = "response_failure_code") val responseFailureCode: String?,
    @ColumnInfo(name = "response_failure_retryable") val responseFailureRetryable: Int?,
    @ColumnInfo(name = "response_failure_message") val responseFailureMessage: String?,
    @ColumnInfo(name = "response_provider_key_id") val responseProviderKeyId: String?,
    @ColumnInfo(name = "response_public_key_blob", typeAffinity = ColumnInfo.BLOB) val responsePublicKeyBlob: ByteArray?,
    @ColumnInfo(name = "response_message") val responseMessage: String?,
)

