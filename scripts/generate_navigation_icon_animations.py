#!/usr/bin/env python3
"""Export Material Symbols' FILL axis as native animated-vector resources.

Requires fonttools and brotli. Pass a Google Fonts Material Symbols Outlined variable
font subset (opsz=24, wght=400, GRAD=0, default rounding, FILL=0..1):
https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:FILL@0..1&icon_names=browse_activity,devices,edit,info,mobile_3,view_cozy&display=block
Request with a current browser User-Agent so Google returns a variable font.

Usage: python3 scripts/generate_navigation_icon_animations.py /path/to/font.woff2

Keep all path commands, including degenerate contours at FILL=1. Optimizing the
two endpoints independently destroys the matching topology required by Android.
The font is a build-time source only; it is not shipped or loaded by the app.
"""

import argparse
from pathlib import Path

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont


SYMBOLS = {
    "browse_activity": 0xF8A5,
    "devices": 0xE1B1,
    "edit": 0xE150,
    "info": 0xE88E,
    "mobile_3": 0xF2DA,
    "view_cozy": 0xEB75,
}


class AndroidPathPen(BasePen):
    def __init__(self, glyphs, units_per_em):
        super().__init__(glyphs)
        self.scale = 24 / units_per_em
        self.commands = []

    def command(self, op, *points):
        coords = []
        for x, y in points:
            coords.extend((x * self.scale, 24 - y * self.scale))
        self.commands.append((op, coords))

    def _moveTo(self, p):
        self.command("M", p)

    def _lineTo(self, p):
        self.command("L", p)

    def _qCurveToOne(self, p1, p2):
        self.command("Q", p1, p2)

    def _curveToOne(self, p1, p2, p3):
        self.command("C", p1, p2, p3)

    def _closePath(self):
        self.command("Z")

    def path_data(self):
        return " ".join(
            op + " " + " ".join(format(v, ".5f").rstrip("0").rstrip(".") or "0" for v in coords)
            for op, coords in self.commands
        ).strip()


def export(font, codepoint, fill):
    glyphs = font.getGlyphSet(location={"FILL": fill})
    pen = AndroidPathPen(glyphs, font["head"].unitsPerEm)
    glyphs[font.getBestCmap()[codepoint]].draw(pen)
    return pen


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    args = parser.parse_args()
    font = TTFont(args.font)
    assert [(axis.axisTag, axis.minValue, axis.maxValue) for axis in font["fvar"].axes] == [
        ("FILL", 0, 1)
    ], "Use a subset with only the FILL axis variable"
    out = Path(__file__).resolve().parents[1] / "app/src/main/res/drawable"
    for name, codepoint in SYMBOLS.items():
        start, middle, end = [export(font, codepoint, fill) for fill in (0, 0.5, 1)]
        topology = lambda pen: [(op, len(coords)) for op, coords in pen.commands]
        assert topology(start) == topology(middle) == topology(end), name
        for (_, a), (_, m), (_, b) in zip(start.commands, middle.commands, end.commands):
            assert all(abs((x + y) / 2 - z) < 0.001 for x, z, y in zip(a, m, b)), name
        assert start.path_data() != end.path_data(), name
        (out / f"avd_nav_{name}.xml").write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols Outlined, Google, Apache 2.0. FILL 0 to 1; opsz 24, wght 400, GRAD 0.
     Generated by scripts/generate_navigation_icon_animations.py. Preserve matching path commands. -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt">
    <aapt:attr name="android:drawable">
        <vector android:width="24dp" android:height="24dp"
            android:viewportWidth="24" android:viewportHeight="24">
            <path android:name="fill" android:fillColor="#FF000000"
                android:pathData="{start.path_data()}" />
        </vector>
    </aapt:attr>
    <target android:name="fill">
        <aapt:attr name="android:animation">
            <objectAnimator android:propertyName="pathData" android:valueType="pathType"
                android:duration="@integer/navigation_icon_selection_duration_ms"
                android:interpolator="@android:interpolator/fast_out_slow_in"
                android:valueFrom="{start.path_data()}"
                android:valueTo="{end.path_data()}" />
        </aapt:attr>
    </target>
</animated-vector>
''')
        print(f"{name}: {len(start.commands)} compatible path commands")


if __name__ == "__main__":
    main()
